/**
 * Copy + WebP-compress sketch images for hero glass orbs.
 * Run from repo root: node scripts/build-sketch-orbs.mjs
 *
 * Source: SKETCH_SOURCE env or E:\Pictures\Sketches (Windows default).
 */
import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";
import sharp from "sharp";

const __dirname = path.dirname(fileURLToPath(import.meta.url));
const root = path.join(__dirname, "..");

const defaultWin = "E:\\Pictures\\Sketches";
const sourceDir =
  process.env.SKETCH_SOURCE ||
  (process.platform === "win32" ? defaultWin : path.join(root, "public/assets/home/sketch-orbs-source"));

const outDir = path.join(root, "public/assets/home/sketch-orbs");
const manifestPath = path.join(root, "src/data/sketch-orb-images.ts");

const exts = new Set([".jpg", ".jpeg", ".png", ".webp"]);

async function main() {
  if (!fs.existsSync(sourceDir)) {
    console.error("Missing sketch source:", sourceDir);
    process.exit(1);
  }
  fs.mkdirSync(outDir, { recursive: true });

  const files = fs
    .readdirSync(sourceDir)
    .filter((n) => exts.has(path.extname(n).toLowerCase()))
    .sort((a, b) => a.localeCompare(b, undefined, { sensitivity: "base" }));

  if (files.length === 0) {
    console.error("No images in", sourceDir);
    process.exit(1);
  }

  const urls = [];
  for (let i = 0; i < files.length; i++) {
    const inPath = path.join(sourceDir, files[i]);
    const base = `sketch-${String(i + 1).padStart(2, "0")}.webp`;
    const outPath = path.join(outDir, base);
    const buf = await sharp(inPath)
      .rotate()
      .resize(768, 768, { fit: "inside", withoutEnlargement: true })
      .webp({ quality: 82, effort: 6 })
      .toBuffer();
    fs.writeFileSync(outPath, buf);
    const url = `/assets/home/sketch-orbs/${base}`;
    urls.push(url);
    console.log(inPath, "->", path.relative(root, outPath), `${(buf.length / 1024).toFixed(1)} KB`);
  }

  const ts = `/** Auto-generated by scripts/build-sketch-orbs.mjs — run after adding sketches to source folder. */
export const SKETCH_ORB_IMAGES = [
${urls.map((u) => `  "${u}",`).join("\n")}
] as const;

export type SketchOrbImageUrl = (typeof SKETCH_ORB_IMAGES)[number];
`;
  fs.writeFileSync(manifestPath, ts, "utf8");
  console.log("Wrote", path.relative(root, manifestPath));
}

main().catch((e) => {
  console.error(e);
  process.exit(1);
});
